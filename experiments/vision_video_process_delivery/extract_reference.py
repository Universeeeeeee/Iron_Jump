"""Extract exact video/inference selection from one retained original GUI window."""
import hashlib
import json
from pathlib import Path
import sys

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

if __name__=='__main__':
    source=Path(sys.argv[1]);output=Path(sys.argv[2]);assert not output.exists()
    gui_path=source/'gui_result.json';work_path=source/'workload_final.json'
    gui=json.loads(gui_path.read_text(encoding='utf-8-sig'))
    work=json.loads(work_path.read_text(encoding='utf-8-sig'))
    assert gui['complete'] and gui['backend']=='original' and gui['saved_preview_replay']
    frames=gui['video_frame_ids'];rows=work['rows'];inferences=rows['inferences'];calls=rows['adapter_calls']
    assert len(frames)==gui['camera']['decoded_frames'] and len(frames)>0
    assert len(inferences)==len(calls)==417
    selected=[]
    for ordinal,(inference,call) in enumerate(zip(inferences,calls)):
        record=inference['record'];meta=record['metadata']
        assert inference['tid']==call['tid'] and call['has_pose']==record['has_pose'] and call['error']==record['error']
        inference_begin=round(record['inference_start_s']*1e9)
        inference_end=round(record['inference_end_s']*1e9)
        assert inference_begin<=call['begin_ns']<=call['end_ns']<=inference_end
        assert call['shape']==[360,640,3] and call['dtype']=='uint8'
        assert meta['frame_index'] in frames
        selected.append(dict(ordinal=ordinal,frame_index=meta['frame_index'],sample_time_s=meta['sample_time_s'],
            timestamp_ms=call['timestamp_ms'],has_pose=record['has_pose'],error=record['error'],shape=call['shape'],dtype=call['dtype']))
    result=dict(reference_case='session_gui_comparison/aa01',backend='original',preview_frame_ids=frames,inferences=selected,
        counts=dict(preview_frames=len(frames),inferences=len(selected),stale_frames_skipped=gui['camera']['stale_frames_skipped']),
        source_sha256={'gui_result.json':sha(gui_path),'workload_final.json':sha(work_path)},
        scope='Actual retained dynamic selection only. Does not contain pose coordinates orpixel hashes; those are generated by the frozen delivery reference pass.')
    output.write_text(json.dumps(result,indent=2),encoding='utf-8')
    print(json.dumps(result['counts']))
